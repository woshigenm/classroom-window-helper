# ============================================================
#  screenguard_test.ps1 -- 屏幕监控守卫的 A/B 自测
#
#  做法:
#    1) bin\bypass_screen.ini 写 enabled=0 -> 跑 screenguard_test --inject:
#       两次抓屏应该不同 (抓的是实时桌面) => 基线;
#    2) 写 enabled=1 -> 再跑一次: 两次抓屏应该相同 (第二次是定格帧);
#    3) 恢复原来的 ini 内容。
#
#  用法: powershell -NoProfile -ExecutionPolicy Bypass -File tests\screenguard_test.ps1
#  ⚠ 本文件必须存成 "UTF-8 with BOM" (PowerShell 5.1 否则按 ANSI 读)。
# ============================================================

$ErrorActionPreference = 'Stop'

$root = Split-Path -Parent $PSScriptRoot
$bin  = Join-Path $root 'bin'
$exe  = Join-Path $bin 'screenguard_test.exe'
$dll  = Join-Path $bin 'bypass_hook32.dll'
$ini  = Join-Path $bin 'bypass_screen.ini'

foreach ($p in @($exe, $dll, (Join-Path $bin 'inject32.exe'))) {
    if (-not (Test-Path $p)) { throw "missing $p - run: make.bat all screentest" }
}

$oldIni = $null
if (Test-Path $ini) { $oldIni = Get-Content $ini -Raw }

function Write-Ini([int]$enabled, [string]$mode) {
    $body = "; auto-generated by tests\screenguard_test.ps1`r`nenabled=$enabled`r`nmode=$mode`r`n"
    [System.IO.File]::WriteAllText($ini, $body, (New-Object System.Text.UTF8Encoding $false))
}

function Run-Case([string]$tag) {
    Push-Location $bin
    try {
        $out = & $exe --inject 'bypass_hook32.dll' 2>&1 | Out-String
    } finally {
        Pop-Location
    }
    $m = [regex]::Match($out, 'SUMMARY .*frozen=(\d)')
    if (-not $m.Success) {
        Write-Host $out
        throw "${tag}: no SUMMARY line"
    }
    Write-Host ("  {0}: frozen={1}" -f $tag, $m.Groups[1].Value)
    return [int]$m.Groups[1].Value
}

try {
    Write-Host 'case 1/2: guard OFF (expect frozen=0)'
    Write-Ini 0 'freeze'
    $off = Run-Case 'off'

    Write-Host 'case 2/2: guard ON  (expect frozen=1)'
    Write-Ini 1 'freeze'
    $on = Run-Case 'on'
} finally {
    if ($null -ne $oldIni) {
        [System.IO.File]::WriteAllText($ini, $oldIni, (New-Object System.Text.UTF8Encoding $false))
    } else {
        Remove-Item $ini -ErrorAction SilentlyContinue
    }
}

if ($off -eq 0 -and $on -eq 1) {
    Write-Host 'VERDICT PASS (live capture without the guard, frozen frame with it)'
    exit 0
}
Write-Host "VERDICT FAIL (off=$off on=$on)"
exit 1
